import { test, expect } from './fixtures'

// Drives the new modules through the real UI: SEC Nigeria plan generator, ESG report
// quality checklist, CRAFT Governance Scorecard (with the founder-protection overlay)
// and the Corrective Action & Evidence Hub links between them.
test('plan generator, quality checklist, CRAFT scorecard and CAP hub work end to end', async ({ signedIn: page }) => {
  await page.goto('/app/workspaces')
  await page.getByLabel('Organization name').fill('Governance E2E Org')
  await page.getByLabel('Country').fill('Nigeria')
  await page.getByRole('button', { name: 'Create organization' }).click()
  await expect(page.getByRole('heading', { name: 'Workspaces' })).toBeVisible()
  await page.getByLabel('New workspace').fill('Readiness')
  await page.getByRole('button', { name: 'Create', exact: true }).click()
  await page.getByRole('link', { name: 'Readiness' }).click()
  const dashboard = page.url()

  // 1. SEC Nigeria IFRS S1/S2 implementation plan
  await page.getByRole('main').getByRole('link', { name: 'IFRS S1/S2 implementation plan (SEC Nigeria)' }).click()
  await expect(page.getByText('Plans are due')).toBeVisible()
  await page.getByLabel('Organisation name').fill('Acme Plc')
  await page.getByLabel('Planning horizon').selectOption('24m')
  await page.getByRole('button', { name: 'Generate implementation plan' }).click()
  await expect(page.getByRole('link', { name: 'Governance arrangements for sustainability reporting, including Board oversight' })).toBeVisible()
  await expect(page.getByRole('cell', { name: 'Key implementation challenges' })).toBeVisible()
  await expect(page.getByText('first in-scope period begins on or after 1 January 2028')).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download Word document' }).click()
  expect((await download).suggestedFilename()).toBe('ifrs-s1-s2-implementation-plan.doc')

  // 2. ESG report quality checklist
  await page.goto(dashboard)
  await page.getByRole('main').getByRole('link', { name: 'ESG report quality checklist' }).click()
  await expect(page.getByText('Release blocker:')).toBeVisible()
  await page.getByLabel('Label (e.g. FY2028 annual report)').fill('FY2028')
  await page.getByLabel('Period start').fill('2028-01-01')
  await page.getByLabel('Period end').fill('2028-12-31')
  await page.getByLabel(/Covered by the SEC Nigeria circular/).check()
  await page.getByRole('button', { name: 'Create period' }).click()
  await page.getByRole('link', { name: 'FY2028' }).click()
  await expect(page.getByText(/Score 0\/100 — .*Approval blocked/)).toBeVisible()
  await expect(page.getByText('periods beginning on or after 2028-01-01')).toBeVisible()
  await page.getByRole('row', { name: /S1-03 Materiality process/ }).getByRole('button', { name: 'Open' }).click()
  await page.getByLabel('Owner').fill('Head of Sustainability')
  await page.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByRole('row', { name: /S1-03 Materiality process/ })).toContainText('Head of Sustainability')
  // Met is refused without accepted evidence.
  await page.getByLabel('Status').selectOption('met')
  await page.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByRole('alert')).toContainText('Met requires linked evidence accepted')
  await page.getByRole('button', { name: 'Raise corrective action' }).click()

  // 3. The raised CAP appears in the hub with the check context and lifecycle tiles.
  await page.goto(dashboard)
  await page.getByRole('main').getByRole('link', { name: 'Corrective Action & Evidence Hub' }).click()
  await expect(page.getByText('Effectiveness review pending')).toBeVisible()
  await page.getByRole('link', { name: /FY2028 · S1-03 Materiality process/ }).click()
  await expect(page.getByRole('heading', { name: 'Finding analysis' })).toBeVisible()
  await page.getByLabel('Root cause (why the gap occurred)').fill('No owner for the materiality process')
  await page.getByRole('button', { name: 'Save changes' }).click()
  await page.reload()
  await expect(page.getByLabel('Root cause (why the gap occurred)')).toHaveValue('No owner for the materiality process')

  // 4. CRAFT Governance Scorecard with the founder-protection overlay
  await page.goto(dashboard)
  await page.getByRole('main').getByRole('link', { name: 'Governance assessments & CRAFT Scorecard' }).click()
  await page.getByLabel('Framework').selectOption('CRAFT')
  await page.getByLabel('Reporting period').fill('FY2026')
  await page.getByLabel(/funds or supports innovation/).check()
  await page.getByRole('button', { name: 'New assessment' }).click()
  await page.getByRole('main').getByRole('link', { name: 'CRAFT', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'CRAFT Governance Scorecard v1 — FY2026' })).toBeVisible()
  await page.getByRole('button', { name: 'Scoring Wizard' }).click()
  const ldr1 = page.locator('div', { has: page.getByText('LDR-1 · Board mandate and composition') }).last()
  await ldr1.getByLabel('Rubric score').selectOption('4')
  await ldr1.getByLabel('Evidence held').check()
  await ldr1.getByRole('button', { name: 'Save' }).click()
  await expect(ldr1.getByText('completed')).toBeVisible()
  await page.getByRole('button', { name: 'Ethics' }).click()
  await expect(page.getByText('ETH-4 · Fair and transparent founder contracting')).toBeVisible()
  await page.getByRole('button', { name: 'Scorecard' }).click()
  await expect(page.getByText('CRAFT-GS 0.1 — provisional.')).toBeVisible()
  await expect(page.getByText('80', { exact: true })).toBeVisible()
})
